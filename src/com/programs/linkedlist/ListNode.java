package com.programs.linkedlist;

public class ListNode {
	
	int data;      
    ListNode next;      
    
    ListNode(int data1, ListNode next1) {
        this.data = data1;  
        this.next = next1;  
    }
    ListNode(int data1) {
        this.data = data1;  
        this.next = null;   
    }
}
